export function translate(lang: Lang, text: string, vars?: Vars): string {
  const base = lang === "ka" ? (KA[text] ?? text) : text;
  return vars ? base.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? "")) : base;
}

